#!/usr/bin/env node
/**
 * Font to Base64 Converter for jsPDF
 *
 * This script converts a TTF font file to base64 format
 * that can be used with jsPDF's addFileToVFS method
 *
 * Usage:
 *   node convert-font-to-base64.js <path-to-ttf-file> <output-file>
 *
 * Example:
 *   node convert-font-to-base64.js Roboto-Regular.ttf roboto-font-data.ts
 */

const fs = require('fs')
const path = require('path')

// Check arguments
if (process.argv.length < 3) {
  console.error('❌ Error: No font file specified')
  console.log('\n📖 Usage:')
  console.log('  node convert-font-to-base64.js <path-to-ttf-file> [output-file]\n')
  console.log('📝 Example:')
  console.log('  node convert-font-to-base64.js Roboto-Regular.ttf roboto-font-data.ts\n')
  process.exit(1)
}

const fontPath = process.argv[2]
const outputPath = process.argv[3] || 'font-data.ts'

// Check if font file exists
if (!fs.existsSync(fontPath)) {
  console.error(`❌ Error: Font file not found: ${fontPath}`)
  process.exit(1)
}

console.log('🔄 Converting font to base64...')
console.log(`   Input: ${fontPath}`)
console.log(`   Output: ${outputPath}`)

try {
  // Read font file
  const fontBuffer = fs.readFileSync(fontPath)
  const base64Font = fontBuffer.toString('base64')

  // Get font name from filename
  const fontName = path.basename(fontPath, path.extname(fontPath))

  // Generate TypeScript file content
  const tsContent = `/**
 * ${fontName} Font Data for jsPDF with Cyrillic support
 * 
 * Auto-generated by convert-font-to-base64.js
 * Source: ${path.basename(fontPath)}
 * Generated: ${new Date().toISOString()}
 * Size: ${Math.round(fontBuffer.length / 1024)} KB (original), ${Math.round(base64Font.length / 1024)} KB (base64)
 * 
 * Font License: Please ensure you have the right to use this font
 */

import { jsPDF } from "jspdf"

/**
 * Base64-encoded font data
 */
export const robotoFontData = "${base64Font}"

/**
 * Adds ${fontName} font to a jsPDF document
 * 
 * @param doc - The jsPDF document instance
 * @returns boolean - true if font was loaded successfully
 */
export const addRobotoFont = (doc: jsPDF): boolean => {
  if (!robotoFontData || robotoFontData === "") {
    console.warn("⚠️  Font data is not loaded.")
    doc.setFont("helvetica", "normal")
    return false
  }

  try {
    // Add font to virtual file system
    doc.addFileToVFS("${path.basename(fontPath)}", robotoFontData)
    
    // Register the font with jsPDF
    doc.addFont("${path.basename(fontPath)}", "Roboto", "normal")
    
    // Set as the active font
    doc.setFont("Roboto", "normal")
    
    console.info("✓ ${fontName} font loaded successfully")
    return true
  } catch (error) {
    console.error("Failed to load ${fontName} font:", error)
    doc.setFont("helvetica", "normal")
    return false
  }
}

export default addRobotoFont
`

  // Write output file
  fs.writeFileSync(outputPath, tsContent, 'utf8')

  console.log('✅ Conversion successful!')
  console.log(`   Original size: ${Math.round(fontBuffer.length / 1024)} KB`)
  console.log(`   Base64 size: ${Math.round(base64Font.length / 1024)} KB`)
  console.log(`   Output written to: ${outputPath}`)

} catch (error) {
  console.error('❌ Error during conversion:', error.message)
  process.exit(1)
}

